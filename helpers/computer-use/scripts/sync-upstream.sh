#!/usr/bin/env bash
# Keeps helpers/computer-use/upstream/ equal to an upstream release plus our patches/.
#
#   scripts/sync-upstream.sh <tag>     replace upstream/ with release <tag>, re-apply patches/,
#                                      regenerate upstream/Cargo.toml and the record in UPSTREAM.md
#   scripts/sync-upstream.sh --verify  check upstream/ is exactly the recorded release plus patches/
#
# Tags look like cua-driver-rs-v0.35.2 (https://github.com/trycua/cua/tags). The steps that
# follow a sync (build, tests, benches) are listed in upstream/UPSTREAM.md.
set -euo pipefail

repo_url=https://github.com/trycua/cua
src_root=libs/cua-driver/rust
# The macOS backend and what it needs. Nothing else of the upstream workspace is vendored.
crates=(cua-driver-core cua-driver-contract platform-macos cursor-overlay cua-cursor-motion pip-preview)
# cua-driver-core embeds these with include_str!.
extra_dirs=(Skills/cua-driver)
# Copied from the upstream workspace root.
root_files=(THIRD_PARTY_NOTICES.md)

helper="$(cd "$(dirname "$0")/.." && pwd)"
up="$helper/upstream"
patches="$helper/patches"
top="$(git -C "$helper" rev-parse --show-toplevel)"
up_rel="${up#"$top"/}"
tmp_base="${TMPDIR:-/tmp}"
tmp_base="${tmp_base%/}"

work=""
cleanup() {
  # Only ever the scratch folder this run made.
  case "$work" in
    "$tmp_base"/brigadier-cu-sync.*) rm -rf -- "$work" ;;
  esac
}
trap cleanup EXIT
work="$(mktemp -d "$tmp_base/brigadier-cu-sync.XXXXXX")"

die() { echo "sync-upstream: $*" >&2; exit 1; }

patch_files() {
  find "$patches" -maxdepth 1 -name '*.diff' -type f 2>/dev/null | sort
}

# sha256 of every vendored file, one line each, in a stable order.
file_hashes() {
  (cd "$1" && find crates Skills LICENSE.md "${root_files[@]}" -type f -print0 | LC_ALL=C sort -z |
    xargs -0 shasum -a 256)
}

if [ "${1:-}" = "--verify" ]; then
  [ -f "$up/PRISTINE.sha256" ] || die "no upstream/PRISTINE.sha256; run a sync first"
  copy="$work/copy"
  mkdir -p "$copy"
  (cd "$up" && cp -R crates Skills LICENSE.md "${root_files[@]}" "$copy/")
  # Undo our patches, last first, then compare with the release as it was fetched.
  patch_list="$(patch_files)"
  if [ -n "$patch_list" ]; then
    while IFS= read -r p; do
      (cd "$copy" && git apply -R -p1 "$p") || die "patch $(basename "$p") does not reverse cleanly"
    done < <(printf '%s\n' "$patch_list" | sort -r)
  fi
  if ! diff -u "$up/PRISTINE.sha256" <(file_hashes "$copy") >"$work/diff"; then
    cat "$work/diff" >&2
    die "upstream/ differs from the recorded release plus patches/"
  fi
  echo "upstream/ is the recorded release plus $(printf '%s' "$patch_list" | grep -c . || true) patch(es)"
  exit 0
fi

tag="${1:-}"
[ -n "$tag" ] || die "usage: scripts/sync-upstream.sh <tag> | --verify"
case "$tag" in cua-driver-rs-v*) ;; *) die "expected a cua-driver-rs-v* release tag, got $tag" ;; esac

echo "+ fetching $tag"
git clone --quiet --filter=blob:none --no-checkout --depth 1 --branch "$tag" "$repo_url" "$work/src"
sparse=("$src_root/crates/${crates[0]}")
for c in "${crates[@]:1}"; do sparse+=("$src_root/crates/$c"); done
for d in "${extra_dirs[@]}"; do sparse+=("$src_root/$d"); done
git -C "$work/src" sparse-checkout set "${sparse[@]}"
git -C "$work/src" checkout --quiet "$tag"
commit="$(git -C "$work/src" rev-parse HEAD)"
commit_date="$(git -C "$work/src" log -1 --format=%cs)"
src="$work/src/$src_root"
[ -f "$work/src/LICENSE.md" ] || die "the release has no LICENSE.md at its root"
grep -q '^MIT License' "$work/src/LICENSE.md" || die "the release's LICENSE.md is not the MIT licence"

echo "+ replacing upstream/ with $tag ($commit)"
mkdir -p "$up/crates" "$up/Skills"
for c in "${crates[@]}"; do
  [ -d "$src/crates/$c" ] || die "$tag has no crate $c"
  mkdir -p "$up/crates/$c"
  rsync -a --delete "$src/crates/$c/" "$up/crates/$c/"
done
for d in "${extra_dirs[@]}"; do
  mkdir -p "$up/$d"
  rsync -a --delete "$src/$d/" "$up/$d/"
done
# A crate that is no longer in the list goes.
for existing in "$up"/crates/*/; do
  name="$(basename "$existing")"
  keep=false
  for c in "${crates[@]}"; do [ "$c" = "$name" ] && keep=true; done
  if ! $keep; then
    case "$existing" in "$up"/crates/?*/) rm -rf -- "$existing" ;; esac
  fi
done
cp "$work/src/LICENSE.md" "$up/LICENSE.md"
for f in "${root_files[@]}"; do cp "$src/$f" "$up/$f"; done

file_hashes "$up" >"$up/PRISTINE.sha256"

# The upstream workspace manifest, with `members` cut to the crates above.
{
  echo "# Generated by scripts/sync-upstream.sh from the $tag workspace manifest."
  echo "# Only \`members\` differs from upstream. Do not edit by hand."
  awk -v list="$(IFS=,; echo "${crates[*]}")" '
    /^members = \[/ { print "members = ["; n = split(list, m, ","); for (i = 1; i <= n; i++) print "    \"crates/" m[i] "\","; print "]"; skip = 1; next }
    skip && /^\]/ { skip = 0; next }
    !skip { print }
  ' "$src/Cargo.toml"
} >"$up/Cargo.toml"

patch_list="$(patch_files)"
if [ -n "$patch_list" ]; then
  while IFS= read -r p; do
    echo "+ applying $(basename "$p")"
    git -C "$top" apply --directory="$up_rel" -p1 "$p" || die "patch $(basename "$p") no longer applies; refresh or drop it"
  done <<<"$patch_list"
fi

# Ignored files would silently drop out of the commit. Only what the sync writes is checked: a
# lock a direct cargo run left in upstream/ is ignored on purpose.
vendored=("$up_rel/crates" "$up_rel/Skills" "$up_rel/LICENSE.md" "$up_rel/Cargo.toml")
for f in "${root_files[@]}"; do vendored+=("$up_rel/$f"); done
ignored="$(git -C "$top" ls-files --others --ignored --exclude-standard -- "${vendored[@]}" || true)"
[ -z "$ignored" ] || die "these vendored files are ignored by .gitignore: $ignored"

# The record in UPSTREAM.md, between the sync markers.
pristine_sum="$(shasum -a 256 "$up/PRISTINE.sha256" | cut -d' ' -f1)"
{
  echo "<!-- sync:begin (written by scripts/sync-upstream.sh) -->"
  echo "| | |"
  echo "|---|---|"
  echo "| Repository | $repo_url |"
  echo "| Tag | \`$tag\` |"
  echo "| Commit | \`$commit\` ($commit_date) |"
  echo "| Path in the repository | \`$src_root\` |"
  echo "| Crates | $(printf '`%s` ' "${crates[@]}")|"
  echo "| Also copied | $(printf '`%s/` ' "${extra_dirs[@]}")\`LICENSE.md\` $(printf '`%s` ' "${root_files[@]}")|"
  echo "| Files | $(wc -l <"$up/PRISTINE.sha256" | tr -d ' ') (sha256 of PRISTINE.sha256: \`$pristine_sum\`) |"
  echo
  if [ -n "$patch_list" ]; then
    echo "Patches applied, in order:"
    echo
    while IFS= read -r p; do
      echo "- \`patches/$(basename "$p")\`: $(sed -n 's/^Why: //p' "$p" | head -1)"
    done <<<"$patch_list"
  else
    echo "Patches applied: none."
  fi
  echo "<!-- sync:end -->"
} >"$work/record.md"
if [ -f "$up/UPSTREAM.md" ] && grep -q '<!-- sync:begin' "$up/UPSTREAM.md"; then
  awk -v rec="$work/record.md" '
    /<!-- sync:begin/ { while ((getline line < rec) > 0) print line; skip = 1; next }
    skip && /<!-- sync:end -->/ { skip = 0; next }
    !skip { print }
  ' "$up/UPSTREAM.md" >"$work/UPSTREAM.md"
  cp "$work/UPSTREAM.md" "$up/UPSTREAM.md"
else
  cat "$work/record.md" >>"$up/UPSTREAM.md"
fi

echo "+ synced $tag ($commit)"
echo "next: the steps under \"Updating\" in upstream/UPSTREAM.md"
